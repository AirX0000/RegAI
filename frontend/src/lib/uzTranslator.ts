function applyCase(sourceWord: string, targetWord: string): string {
    if (!sourceWord || !targetWord) return targetWord;
    if (sourceWord === sourceWord.toUpperCase() && sourceWord.length > 1) {
        return targetWord.toUpperCase();
    }
    if (sourceWord[0] === sourceWord[0].toUpperCase()) {
        return targetWord.charAt(0).toUpperCase() + targetWord.slice(1);
    }
    return targetWord;
}

export function translateToUzbek(ru: string, en: string): string {
    const trimmedRu = (ru || '').trim();
    const trimmedEn = (en || '').trim();

    if (UZ_EXACT_PHRASES[ru]) return UZ_EXACT_PHRASES[ru];
    if (UZ_EXACT_PHRASES[trimmedRu]) return UZ_EXACT_PHRASES[trimmedRu];
    if (UZ_EXACT_PHRASES[en]) return UZ_EXACT_PHRASES[en];
    if (UZ_EXACT_PHRASES[trimmedEn]) return UZ_EXACT_PHRASES[trimmedEn];

    // Base on English string (Latin script) so we never leak Cyrillic into O'zbekcha
    let result = en || ru || '';
    if (!result) return '';

    for (const [pattern, replacement] of PHRASE_REPLACEMENTS) {
        result = result.replace(pattern, replacement);
    }

    result = result.replace(/\b([A-Za-z]+)\b/g, (match) => {
        const lower = match.toLowerCase();
        // Preserve technical acronyms
        if (['ifrs', 'ias', 'isa', 'nas', 'uzs', 'usd', 'eur', 'vat', 'cit', 'ecl', 'rou', 'wacc', 'npv', 'irr', 'ebitda', 'odata', 'sso', 'oidc', 'api', 'pdf', 'xlsx', 'csv', 'json', 'xml', 'ai', 'id', 'url', 'ip', 'tls', 'iso', 'iec'].includes(lower)) {
            return match;
        }
        if (WORD_MAP[lower]) {
            return applyCase(match, WORD_MAP[lower]);
        }
        return match;
    });

    return result;
}
