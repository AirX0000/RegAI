// Register all resource pairs into UZ_EXACT_PHRASES for instant exact lookup
const enMap = resources.en.translation as Record<string, string>;
const ruMap = resources.ru.translation as Record<string, string>;
const uzMap = resources.uz.translation as Record<string, string>;
for (const key of Object.keys(uzMap)) {
    const uzVal = uzMap[key];
    if (ruMap[key] && !UZ_EXACT_PHRASES[ruMap[key]]) {
        UZ_EXACT_PHRASES[ruMap[key]] = uzVal;
    }
    if (enMap[key] && !UZ_EXACT_PHRASES[enMap[key]]) {
        UZ_EXACT_PHRASES[enMap[key]] = uzVal;
    }
}

export function normalizeLang(raw?: string | null): 'ru' | 'en' | 'uz' {
    const l = (raw || 'ru').toLowerCase();
    if (l.startsWith('en')) return 'en';
    if (l.startsWith('uz')) return 'uz';
    return 'ru';
}

export function getActiveLang(): 'ru' | 'en' | 'uz' {
    return normalizeLang(i18n.language || (typeof window !== 'undefined' ? localStorage.getItem('i18nextLng') : 'ru'));
}

/**
 * Trilingual helper: returns Russian when 'ru' is active, English when 'en' is active,
 * and Uzbek (O'zbekcha) when 'uz' is active.
 */
export function tr(ru: string, en: string, uz?: string): string {
    const lang = getActiveLang();
    if (lang === 'ru') return ru;
    if (lang === 'en') return en;
    if (uz !== undefined && uz !== '') return uz;
    return translateToUzbek(ru, en);
}

